import puppeteer from 'puppeteer-core'
import fs from 'node:fs'
const B = 'http://localhost:5199'
const wo = JSON.parse(fs.readFileSync('../03-原型/src/mock/workOrders.json', 'utf8'))
const paid = wo.find(w => w.type === '商业服务' && w.status === '待派单')
const pub = wo.find(w => w.type === '公共区域维修' && w.assignee)
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--no-sandbox'] })
const p = await b.newPage()
await p.setViewport({ width: 390, height: 844 })
const errs = []
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
const sleep = ms => new Promise(r => setTimeout(r, ms))
const txt = async () => (await p.evaluate(() => document.body.innerText)).replace(/\n/g, '|')
await p.goto(`${B}/#/pages/login/index`, { waitUntil: 'networkidle2' }); await sleep(1000)
await p.evaluate(() => document.querySelectorAll('.pcard')[0].click()); await sleep(1200)
console.log('付费单', paid.woNo, paid.serviceName, paid.totalFee)
await p.goto(`${B}/#/pages/wo/detail?id=${paid.woId}`, { waitUntil: 'networkidle2' }); await sleep(1200)
let t = await txt()
console.log('详情含服务项目:', t.includes(paid.serviceName), '| 含下单总价:', t.includes('下单总价'), '| 金额对齐:', t.includes('¥' + paid.totalFee))
console.log('价目码:', paid.priceCode, t.includes(paid.priceCode))
console.log('公区单', pub.woNo, pub.type)
await p.goto(`${B}/#/pages/wo/detail?id=${pub.woId}`, { waitUntil: 'networkidle2' }); await sleep(1200)
t = await txt()
console.log('公区单无提成:', !t.includes('本单提成'), '| 有公区说明:', t.includes('不向业主收费'))
console.log('errs', errs.length ? errs.slice(0, 3) : 'none')
await b.close()
